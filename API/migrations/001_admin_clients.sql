BEGIN;

CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_name VARCHAR(200) NOT NULL UNIQUE,
    business_number VARCHAR(100),
    email_address VARCHAR(255),
    phone_number_1 VARCHAR(40),
    phone_number_2 VARCHAR(40),
    phone_number_3 VARCHAR(40),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE physical_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL UNIQUE REFERENCES clients(id) ON DELETE CASCADE,
    country VARCHAR(100),
    city VARCHAR(150),
    street VARCHAR(200),
    building_number VARCHAR(30),
    apartment_number VARCHAR(30),
    postal_code VARCHAR(30)
);

CREATE TABLE mailing_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL UNIQUE REFERENCES clients(id) ON DELETE CASCADE,
    mailing_name VARCHAR(200),
    country VARCHAR(100),
    city VARCHAR(150),
    street VARCHAR(200),
    building_number VARCHAR(30),
    apartment_number VARCHAR(30),
    postal_code VARCHAR(30)
);

CREATE TABLE client_namespaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    namespace_name VARCHAR(63) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE namespace_limits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace_id BIGINT NOT NULL UNIQUE REFERENCES client_namespaces(id) ON DELETE CASCADE,
    cpu_limit VARCHAR(50),
    memory_limit VARCHAR(50),
    pv_limit INTEGER CHECK (pv_limit IS NULL OR pv_limit >= 0),
    storage_limit VARCHAR(50)
);

CREATE TABLE client_domains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    domain_name VARCHAR(253) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE helm_repositories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    repository_name VARCHAR(200) NOT NULL,
    repository_url TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (client_id, repository_name)
);

CREATE TABLE client_helm_releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    namespace_id BIGINT REFERENCES client_namespaces(id) ON DELETE SET NULL,
    repository_id BIGINT REFERENCES helm_repositories(id) ON DELETE SET NULL,
    helm_name VARCHAR(200) NOT NULL,
    chart_name VARCHAR(200) NOT NULL,
    chart_version VARCHAR(100),
    release_name VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE client_yaml_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    namespace_id BIGINT REFERENCES client_namespaces(id) ON DELETE SET NULL,
    original_filename VARCHAR(255) NOT NULL,
    storage_path TEXT NOT NULL,
    content_type VARCHAR(150),
    file_size BIGINT CHECK (file_size IS NULL OR file_size >= 0),
    sha256 CHAR(64),
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_clients_business_number
    ON clients(business_number);

CREATE INDEX idx_client_namespaces_client
    ON client_namespaces(client_id);

CREATE INDEX idx_client_domains_client
    ON client_domains(client_id);

CREATE INDEX idx_helm_releases_client
    ON client_helm_releases(client_id);

CREATE INDEX idx_yaml_files_client
    ON client_yaml_files(client_id);

COMMIT;
