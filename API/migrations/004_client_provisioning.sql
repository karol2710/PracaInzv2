BEGIN;

-- Existing clients have not been reconciled with Kubernetes yet.
ALTER TABLE clients
    ADD COLUMN provisioning_status VARCHAR(24) NOT NULL DEFAULT 'unverified',
    ADD COLUMN rate_limit_rps INTEGER CHECK (rate_limit_rps > 0),
    ADD CONSTRAINT clients_provisioning_status_check CHECK (
        provisioning_status IN ('unverified', 'pending', 'provisioning', 'active', 'failed', 'suspended', 'deleting')
    );
ALTER TABLE clients ALTER COLUMN provisioning_status SET DEFAULT 'pending';

-- A domain must be explicitly associated with a backend before publishing it.
ALTER TABLE client_domains
    ADD COLUMN namespace_id BIGINT REFERENCES client_namespaces(id) ON DELETE RESTRICT,
    ADD COLUMN backend_service VARCHAR(63),
    ADD COLUMN backend_port INTEGER CHECK (backend_port BETWEEN 1 AND 65535),
    ADD COLUMN certificate_environment VARCHAR(10) NOT NULL DEFAULT 'production'
        CHECK (certificate_environment IN ('production', 'staging'));

-- Retain the identity of the namespace created by the provisioner.
ALTER TABLE client_namespaces ADD COLUMN kubernetes_uid TEXT;

ALTER TABLE client_helm_releases
    ADD COLUMN chart_sha256 CHAR(64),
    ADD COLUMN deployment_status VARCHAR(16) NOT NULL DEFAULT 'unverified'
        CHECK (deployment_status IN ('unverified', 'pending', 'validated', 'deploying', 'deployed', 'failed'));

ALTER TABLE client_yaml_files
    ADD COLUMN helm_release_id BIGINT REFERENCES client_helm_releases(id) ON DELETE RESTRICT;
CREATE INDEX idx_client_yaml_files_release ON client_yaml_files(helm_release_id);

-- Durable operation record. The API must claim jobs transactionally and reconcile
-- Kubernetes state before retrying an interrupted operation.
CREATE TABLE client_provisioning_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
    request_key UUID NOT NULL UNIQUE,
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'running', 'succeeded', 'failed')),
    current_step VARCHAR(80) NOT NULL DEFAULT 'queued',
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    error_code VARCHAR(100),
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK ((status IN ('succeeded', 'failed')) = (finished_at IS NOT NULL))
);
CREATE UNIQUE INDEX idx_client_one_open_provisioning_job
    ON client_provisioning_jobs(client_id) WHERE status IN ('pending', 'running');
CREATE INDEX idx_client_provisioning_jobs_queue
    ON client_provisioning_jobs(status, created_at);

COMMIT;