BEGIN;

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    login VARCHAR(100) NOT NULL,
    password_hash TEXT NOT NULL,

    role VARCHAR(20) NOT NULL
        CHECK (role IN ('admin', 'client')),

    client_id BIGINT
        REFERENCES clients(id)
        ON DELETE RESTRICT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login_at TIMESTAMPTZ,

    CONSTRAINT app_users_role_client_check
        CHECK (
            (role = 'admin' AND client_id IS NULL)
            OR
            (role = 'client' AND client_id IS NOT NULL)
        )
);

CREATE UNIQUE INDEX idx_app_users_login_lower
    ON app_users (LOWER(login));

CREATE INDEX idx_app_users_client_id
    ON app_users (client_id);

COMMIT;